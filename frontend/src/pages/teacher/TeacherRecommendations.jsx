import { useEffect, useState } from 'react'
import { getTeacherRecommendations } from '../../services/teacherService.js'
import { formatLabel } from '../../services/format.js'

export default function TeacherRecommendations() {
  const [recs, setRecs] = useState([])
  const [error, setError] = useState('')

  useEffect(() => {
    getTeacherRecommendations().then(setRecs).catch((e) => setError(e.message))
  }, [])

  if (error) return <div className="alert">{error}</div>

  return (
    <div className="page">
      <div className="panel">
        <h3>Recommendations Generated by the ML System ({recs.length})</h3>
        <p className="muted">Every recommendation includes its explanation so students and teachers understand why it was made.</p>
        <div className="rec-history">
          {recs.map((r) => (
            <div className="rec-card static" key={r.id}>
              <div className="rec-top">
                <div>
                  <span className="rec-kicker">{r.student_name || 'Student'}{r.lesson_title ? ` · ${r.lesson_title}` : ''}</span>
                  <h3>{r.recommended_format_label || formatLabel(r.recommended_format)}</h3>
                </div>
                <div className="confidence">
                  <strong>{Math.round(r.confidence * 100)}%</strong>
                  <small>{r.difficulty}</small>
                </div>
              </div>
              <p className="rec-reason">{r.reason}</p>
              <span className="muted small">{r.created_at?.slice(0, 16).replace('T', ' ')}</span>
            </div>
          ))}
          {recs.length === 0 && <p className="muted">No recommendations yet.</p>}
        </div>
      </div>
    </div>
  )
}
